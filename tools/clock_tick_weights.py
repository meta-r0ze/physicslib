"""Equal weights for the one-tick steps in an aligned placement (exploration; no data).

In a placement where SliceHop's D4 clock axis is aligned with the E8 clock plane
(tools/clock_slice_alignment.py: slice D3 inside the clock-plane stabilizer A4,
clock-axis roots reading +-1), the receiver's forward tick steps are the six D4
roots reading +1. This script checks that the slice group W(D3), generated by
reflections in the slice roots, fixes the clock (every slice root is clock-silent),
maps the forward set to itself, and acts on it as ONE orbit. By Closure the six
forward steps then carry equal weight; the same holds for the six backward steps.
"""
import numpy as np, itertools, collections
G=np.array([[2,0,-1,0,0,0,0,0],[0,2,0,-1,0,0,0,0],[-1,0,2,-1,0,0,0,0],[0,-1,-1,2,-1,0,0,0],
[0,0,0,-1,2,-1,0,0],[0,0,0,0,-1,2,-1,0],[0,0,0,0,0,-1,2,-1],[0,0,0,0,0,0,-1,2]])
cu=np.array([1,0,0,0,0,0,0,0]); cv=np.array([0,-2,-1,1,-1,0,0,0])
ip=lambda a,b:int(np.asarray(a)@G@np.asarray(b))
ph=lambda z:(lambda r: r if r<=21 else r-43)((ip(z,cu)-2*ip(z,cv))%43)
simple=[tuple(int(x) for x in np.eye(8,dtype=int)[i]) for i in range(8)]
roots=set(simple); fr=list(roots)
while fr:
    new=[]
    for r in fr:
        for s in simple:
            t=tuple(int(a-ip(r,s)*b) for a,b in zip(r,s))
            if t not in roots: roots.add(t); new.append(t)
    fr=new
roots=sorted(roots)
A4=[r for r in roots if ip(r,cu)==0 and ip(r,cv)==0]
def closure(gens):
    S=set(gens)|{tuple(-x for x in g) for g in gens}; fr=list(S)
    while fr:
        new=[]
        for r in fr:
            for g in gens:
                t=tuple(int(a-ip(r,g)*b) for a,b in zip(r,g))
                if t not in S: S.add(t); new.append(t)
        fr=new
    return S
# all A3 paths (a,b,c) in A4: <a,b>=-1,<b,c>=-1,<a,c>=0
import collections, itertools
key_found=None
# find one aligned placement
for a,b,c in itertools.permutations(A4,3):
    if ip(a,b)!=-1 or ip(b,c)!=-1 or ip(a,c)!=0: continue
    D3=closure([a,b,c])
    if len(D3)!=12: continue
    for beta in roots:
        if ip(beta,b)!=1 or ip(beta,a)!=0 or ip(beta,c)!=0: continue
        D4=closure([a,b,c,beta])
        if len(D4)!=24: continue
        cw=[r for r in D4 if r not in D3]
        if sorted(ph(r) for r in cw)==[-1]*6+[1]*6:
            key_found=(a,b,c,beta,D3,D4,cw); break
    if key_found: break
a,b,c,beta,D3,D4,cw=key_found
fwd=[r for r in cw if ph(r)==1]
def refl(v,s): return tuple(int(x-ip(v,s)*y) for x,y in zip(v,s))
# group generated by reflections in the slice roots (W(D3)): fixes clock plane pointwise
def orbits(gens,pts):
    rem=set(pts); out=[]
    while rem:
        p=rem.pop(); o={p}; st=[p]
        while st:
            x=st.pop()
            for g in gens:
                y=refl(x,g)
                if y not in o: o.add(y); st.append(y)
        out.append(o); rem-=o
    return out
o=orbits(D3,fwd)
print("slice reflections preserve the forward set:", all(refl(f,s) in fwd for f in fwd for s in D3))
print("orbits of the 6 forward tick roots under the slice group W(D3):",[len(x) for x in o])
print("every slice root is clock-silent (so W(D3) fixes the clock):", all(ph(s)==0 for s in D3))
# larger: elements of W(A4) preserving the D4 set
o2=orbits([s for s in A4], fwd)
print("orbits under the full clock-plane stabilizer W(A4) (may leave the D4):",[len(x) for x in o2])
# check forward set is {+-e_i + e_3}: pairwise inner products
print("pairwise inner products among forward roots:",dict(collections.Counter(ip(x,y) for x in fwd for y in fwd if x!=y)))
