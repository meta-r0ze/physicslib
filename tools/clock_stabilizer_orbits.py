"""Orbits of the one-tick roots under the clock-plane stabilizer (exploration; no data).

The pointwise stabilizer of the clock plane Z cu + Z cv in W(E8) is generated by
reflections in the roots orthogonal to the plane (Steinberg's fixed-point theorem
for reflection groups). This script:
1. identifies the orthogonal root system (expected A4: 20 roots);
2. generates the group it spans and checks its order;
3. finds the orbits of the 22 roots with clock reading +1, and how they meet the
   two projection classes (1,0) and (-1,-1) from tools/clock_ring_check.py.
By Closure, steps in one orbit carry equal weight.
"""
import collections
import numpy as np

G = np.array([[2,0,-1,0,0,0,0,0],[0,2,0,-1,0,0,0,0],[-1,0,2,-1,0,0,0,0],
              [0,-1,-1,2,-1,0,0,0],[0,0,0,-1,2,-1,0,0],[0,0,0,0,-1,2,-1,0],
              [0,0,0,0,0,-1,2,-1],[0,0,0,0,0,0,-1,2]])
cu = np.array([1,0,0,0,0,0,0,0]); cv = np.array([0,-2,-1,1,-1,0,0,0])
ip = lambda a, b: int(np.asarray(a) @ G @ np.asarray(b))
phase = lambda z: (ip(z, cu) - 2 * ip(z, cv)) % 43

simple = [tuple(int(x) for x in np.eye(8, dtype=int)[i]) for i in range(8)]
roots = set(simple); fr = list(roots)
while fr:
    new = []
    for r in fr:
        for s in simple:
            t = tuple(int(a - ip(r, s) * b) for a, b in zip(r, s))
            if t not in roots:
                roots.add(t); new.append(t)
    fr = new
roots = sorted(roots)

orth = [r for r in roots if ip(r, cu) == 0 and ip(r, cv) == 0]
print("roots orthogonal to the clock plane:", len(orth))
# rank of the orthogonal system
print("rank:", np.linalg.matrix_rank(np.array(orth)))

def reflect(v, a):
    return tuple(int(x - ip(v, a) * y) for x, y in zip(v, a))

# group generated by reflections in orth, as permutations of all 240 roots
idx = {r: i for i, r in enumerate(roots)}
gens = [tuple(idx[reflect(r, a)] for r in roots) for a in orth]
ident = tuple(range(len(roots)))
seen = {ident}; frontier = [ident]
while frontier:
    nxt = []
    for g in frontier:
        for h in gens:
            k = tuple(h[i] for i in g)
            if k not in seen:
                seen.add(k); nxt.append(k)
    frontier = nxt
print("stabilizer order:", len(seen))

plus = [r for r in roots if phase(r) == 1]
cls = lambda r: (ip(r, cu), ip(r, cv))
remaining = set(plus); orbits = []
while remaining:
    r = remaining.pop()
    orb = {r}; stack = [r]
    while stack:
        x = stack.pop()
        for a in orth:
            y = reflect(x, a)
            if y not in orb:
                orb.add(y); stack.append(y)
    remaining -= orb
    orbits.append(orb)
for o in sorted(orbits, key=len):
    print("orbit size", len(o), "projection classes", dict(collections.Counter(cls(r) for r in o)))

# How the two projection classes relate: subtracting the clock-silent root cu.
cu_t = tuple(int(x) for x in cu)
A = [r for r in plus if cls(r) == (1, 0)]
B = set(r for r in plus if cls(r) == (-1, -1))
shifted = [tuple(a - c for a, c in zip(r, cu_t)) for r in A]
print("r - cu is a +1 root of class (-1,-1) for every r in class (1,0):",
      all(s in B for s in shifted) and len(set(shifted)) == len(B))
print("clock reading of cu:", phase(cu_t), " cu fixed by the stabilizer:",
      all(ip(cu_t, a) == 0 for a in orth))
singles = [next(iter(o)) for o in orbits if len(o) == 1]
print("singleton +1 roots:", singles,
      "orthogonal to every stabilizer root:",
      [all(ip(s, a) == 0 for a in orth) for s in singles])
# roots orthogonal to the stabilizer's A4: the complementary system
comp = [r for r in roots if all(ip(r, a) == 0 for a in orth)]
print("roots orthogonal to the A4 (complementary system):", len(comp),
      "rank", np.linalg.matrix_rank(np.array(comp)),
      " contains cu:", cu_t in comp)
